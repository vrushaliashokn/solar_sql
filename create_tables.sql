create DATABASE solar;
USE solar;
create TABLE p1_generation_data (
    DATE_TIME DATETIME NOT NULL,
    PLANT_ID INT NOT NULL,
    SOURCE_KEY VARCHAR(20),
    DC_POWER DOUBLE,
    AC_POWER DOUBLE,
    DAILY_YIELD DOUBLE,
    TOTAL_YIELD DOUBLE,
    PRIMARY KEY (DATE_TIME, PLANT_ID, SOURCE_KEY)
);
create TABLE p2_generation_data (
    DATE_TIME DATETIME NOT NULL,
    PLANT_ID INT NOT NULL,
    SOURCE_KEY VARCHAR(20),
    DC_POWER DOUBLE,
    AC_POWER DOUBLE,
    DAILY_YIELD DOUBLE,
    TOTAL_YIELD DOUBLE,
    PRIMARY KEY (DATE_TIME, PLANT_ID, SOURCE_KEY)
);
create TABLE p1_weather_data (
    DATE_TIME DATETIME NOT NULL,
    PLANT_ID INT NOT NULL,
    SOURCE_KEY VARCHAR(20),
    AMBIENT_TEMPERATURE DOUBLE,
    MODULE_TEMPERATURE DOUBLE,
    IRRADIATION DOUBLE,
    PRIMARY KEY (DATE_TIME, PLANT_ID, SOURCE_KEY)
);
create TABLE p2_weather_data (
    DATE_TIME DATETIME NOT NULL,
    PLANT_ID INT NOT NULL,
    SOURCE_KEY VARCHAR(20),
    AMBIENT_TEMPERATURE DOUBLE,
    MODULE_TEMPERATURE DOUBLE,
    IRRADIATION DOUBLE,
    PRIMARY KEY (DATE_TIME, PLANT_ID, SOURCE_KEY)
);
